import argparse
import csv
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class RamulatorTraceResult:
    trace: str
    config: str
    ramulator_exec: str
    requested_bytes: int
    dram_bytes: int
    read_requests: int
    write_requests: int
    memory_system_cycles: int
    tck_ns: float
    kernel_us: float
    effective_gbps: float
    dram_gbps: float
    stdout: str

    def to_dict(self) -> dict[str, Any]:
        return {
            "trace": self.trace,
            "config": self.config,
            "ramulator_exec": self.ramulator_exec,
            "requested_bytes": self.requested_bytes,
            "dram_bytes": self.dram_bytes,
            "read_requests": self.read_requests,
            "write_requests": self.write_requests,
            "memory_system_cycles": self.memory_system_cycles,
            "tck_ns": self.tck_ns,
            "kernel_us": self.kernel_us,
            "effective_gbps": self.effective_gbps,
            "dram_gbps": self.dram_gbps,
            "source": "ramulator2_hbm3_standalone",
        }


@dataclass(frozen=True)
class TimedHBMRequest:
    request_id: str
    source_core: int
    release_time_ns: float
    address: int
    size_bytes: int


@dataclass(frozen=True)
class TimedHBMCompletion:
    request_id: str
    source_core: int
    release_time_ns: float
    completion_time_ns: float
    raw_completion_cycle: int
    transaction_count: int


@dataclass(frozen=True)
class RamulatorTimedResult:
    requests: tuple[TimedHBMRequest, ...]
    completions: tuple[TimedHBMCompletion, ...]
    requested_bytes: int
    dram_transaction_bytes: int
    dram_transaction_size_bytes: int
    raw_peak_gbps: float
    target_peak_gbps: float
    raw_cycles: int
    tck_ns: float
    kernel_us: float
    effective_gbps: float
    trace: str
    trace_sha256: str
    config: str
    completion_csv: str
    transaction_completion_csv: str
    transaction_completion_sha256: str
    transaction_artifacts_retained: bool
    stdout: str
    source: str = "ramulator2_hbm3_timed_trace"

    def to_dict(self) -> dict[str, Any]:
        return {
            "requests": [request.__dict__ for request in self.requests],
            "completions": [completion.__dict__ for completion in self.completions],
            "requested_bytes": self.requested_bytes,
            "dram_transaction_bytes": self.dram_transaction_bytes,
            "dram_transaction_size_bytes": self.dram_transaction_size_bytes,
            "raw_peak_gbps": self.raw_peak_gbps,
            "target_peak_gbps": self.target_peak_gbps,
            "raw_cycles": self.raw_cycles,
            "tck_ns": self.tck_ns,
            "kernel_us": self.kernel_us,
            "effective_gbps": self.effective_gbps,
            "trace": self.trace,
            "trace_sha256": self.trace_sha256,
            "config": self.config,
            "completion_csv": self.completion_csv,
            "transaction_completion_csv": self.transaction_completion_csv,
            "transaction_completion_sha256": self.transaction_completion_sha256,
            "transaction_artifacts_retained": self.transaction_artifacts_retained,
            "stdout": self.stdout,
            "source": self.source,
        }


def _resolve_ramulator_exec(path: str = "") -> str:
    raw = path or os.environ.get("RAMULATOR2_EXEC", "")
    if raw:
        exe = Path(raw).expanduser().resolve()
        if not exe.exists():
            raise FileNotFoundError(f"Ramulator2 executable not found: {exe}")
        return str(exe)
    repo_root = Path(__file__).resolve().parents[2]
    repo_candidates = [
        repo_root / "build/third_party/ramulator2-build/ramulator2",
        repo_root / "third_party/ramulator2/build/ramulator2",
    ]
    for candidate in repo_candidates:
        if candidate.exists():
            return str(candidate.resolve())
    found = shutil.which("ramulator2")
    if found:
        return found
    raise FileNotFoundError(
        "Ramulator2 executable is required. Run scripts/build_ramulator2.sh, "
        "set RAMULATOR2_EXEC, or pass --ramulator-exec."
    )


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _write_loadstore_trace(csv_trace: Path, out_trace: Path, cacheline_bytes: int) -> tuple[int, int, int]:
    requested = 0
    read_reqs = 0
    write_reqs = 0
    cachelines: set[int] = set()
    with csv_trace.open(encoding="utf-8") as src, out_trace.open("w", encoding="utf-8") as dst:
        reader = csv.DictReader(src)
        for row in reader:
            op = row.get("op", "R").upper()
            addr = int(row["addr"], 16 if str(row["addr"]).lower().startswith("0x") else 10)
            size = int(row.get("size", cacheline_bytes))
            requested += size
            first = addr // cacheline_bytes
            last = (addr + max(size, 1) - 1) // cacheline_bytes
            for line in range(first, last + 1):
                cachelines.add(line)
                dst.write(f"{'ST' if op in {'W', 'ST'} else 'LD'} 0x{line * cacheline_bytes:x}\n")
                if op in {"W", "ST"}:
                    write_reqs += 1
                else:
                    read_reqs += 1
    return requested, len(cachelines) * cacheline_bytes, read_reqs + write_reqs


def _write_hbm3_config(trace: Path, config: Path, channels: int) -> None:
    config.write_text(
        "\n".join(
            [
                "Frontend:",
                "  impl: LoadStoreTrace",
                "  clock_ratio: 1",
                f"  path: {trace}",
                "",
                "MemorySystem:",
                "  impl: GenericDRAM",
                "  clock_ratio: 1",
                "",
                "  DRAM:",
                "    impl: HBM3",
                "    org:",
                "      preset: HBM3_8Gb",
                f"      channel: {channels}",
                "    timing:",
                "      preset: HBM3_2Gbps",
                "",
                "  Controller:",
                "    impl: Generic",
                "    Scheduler:",
                "      impl: FRFCFS",
                "    RefreshManager:",
                "      impl: NoRefresh",
                "    RowPolicy:",
                "      impl: OpenRowPolicy",
                "    plugins:",
                "",
                "  AddrMapper:",
                "    impl: RoBaRaCoCh",
                "",
            ]
        ),
        encoding="utf-8",
    )


