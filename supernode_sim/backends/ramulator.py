#!/usr/bin/env python3
"""Ramulator2 HBM trace backend.

This backend consumes the simulator-neutral HBM trace CSVs generated by
``hacmo/attention/tools/generate_hbm_attention_trace.py`` and runs them through
Ramulator2's standalone trace frontend.
"""

